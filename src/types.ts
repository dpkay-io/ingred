export const VERSION = '0.2.0';

export interface IngredSource {
  name: string;
  type: 'git' | 'local';
  origin: string;
  cachePath: string;
  addedAt: string;
  branch?: string;
  pin?: string;
}

export interface IngredConfig {
  version: 1;
  sources: IngredSource[];
  settings: {
    targets: TargetId[];
    defaultScope: Scope;
  };
  customTargets?: CustomTargetConfig[];
  profiles?: Record<string, ProfileConfig>;
}

export interface IngredientFile {
  filePath: string;
  relativePath: string;
  sourceName: string;
  content: string;
  meta: IngredientMeta;
}

export interface IngredientMeta {
  triggers: string[];
  scope: Scope;
  priority: number;
  always: boolean;
  global: boolean;
  scopeExplicit?: boolean;
  extends?: string;
}

export type Scope = 'engineering' | 'persona';

export interface DetectedStack {
  technologies: Set<string>;
  detectedFiles: Map<string, string[]>;
  workspaceRoot: string;
}

export interface MatchResult {
  ingredient: IngredientFile;
  matchTier: 1 | 2 | 3;
  matchReason: string;
}

export interface CompiledOutput {
  personaSection: string;
  engineeringSection: string;
}

export type TargetId = 'claude' | 'cursor' | 'copilot' | 'agents' | 'gemini' | 'windsurf' | 'cline' | 'aider';

export interface Target {
  id: TargetId | string;
  outputPath: string;
  ensureDir?: string;
  globalOutputPath?: string;
  globalEnsureDir?: string;
  format(compiled: CompiledOutput, stack: DetectedStack): string;
  privateReference(compiledDir: string): string;
}

export interface EmitResult {
  target: TargetId | string;
  location: 'project' | 'global';
  status: 'written' | 'skipped';
  path?: string;
  reason?: string;
}

export interface ExternalMapping {
  files: string[];
  when: {
    dependencies?: string[];
    filesPresent?: string[];
    matchAll?: boolean;
  };
}

export interface CompileResult {
  global: CompiledOutput;
  project: CompiledOutput;
}

export const DEFAULT_META: Readonly<IngredientMeta> = Object.freeze({
  triggers: Object.freeze([]) as unknown as string[],
  scope: 'engineering' as Scope,
  priority: 0,
  always: false,
  global: false,
  extends: undefined,
});

export const INGRED_SENTINEL = '<!-- Generated by ingred. Do not edit manually. Run `ingred mix` to regenerate. -->';

export interface ProjectConfig {
  version: 1;
  privateIngredients: string[];
  excludedIngredients: string[];
  gitignoreSuggested?: boolean;
}

export function defaultProjectConfig(): ProjectConfig {
  return { version: 1, privateIngredients: [], excludedIngredients: [] };
}

/** @deprecated Use ProjectConfig */
export type ProjectPrivacyConfig = ProjectConfig;
/** @deprecated Use defaultProjectConfig */
export const defaultPrivacyConfig = defaultProjectConfig;

export interface CustomTargetConfig {
  id: string;
  outputPath: string;
  format: {
    header?: string;
    personaHeader?: string;
    engineeringHeader?: string;
    commentSyntax: 'html' | 'js' | 'hash' | 'none';
  };
}

export interface WorkspaceConfig {
  profile?: string;
  targets?: string[];
  exclude?: string[];
}

export interface ProfileConfig {
  targets?: string[];
  exclude?: string[];
}

export function defaultConfig(): IngredConfig {
  return {
    version: 1,
    sources: [],
    settings: {
      targets: ['claude', 'cursor', 'copilot', 'agents', 'gemini', 'windsurf', 'cline', 'aider'],
      defaultScope: 'engineering',
    },
  };
}
