import { resolve, join } from 'node:path';
import { loadConfig } from '../core/config.js';
import { collectIngredients } from '../core/sources.js';
import { detectStack } from '../core/detector.js';
import { matchIngredients } from '../core/matcher.js';
import { getProjectId, loadPrivacyConfig, splitByPrivacy } from '../core/privacy.js';
import { getTargetRegistry, registerCustomTargets } from '../core/emitter.js';
import { fileExists, readText } from '../utils/fs.js';
import { INGRED_SENTINEL } from '../types.js';
import { log } from '../utils/logger.js';
import type { IngredientFile, ExternalMapping } from '../types.js';

export async function statusCommand(): Promise<void> {
  const config = await loadConfig();
  const workspaceRoot = resolve('.');

  // ── Sources ────────────────────────────────────────────────────────────────
  log.header('Sources\n');

  if (config.sources.length === 0) {
    log.warn('No sources configured. Run `ingred add <source>` to add one.');
  } else {
    for (const source of config.sources) {
      const { ingredients } = await collectIngredients(source);
      const pinLabel = source.pin ? ` (pinned: ${source.pin})` : '';
      log.info(`  ${source.name}`);
      log.item('    type', source.type);
      log.item('    files', `${ingredients.length} ingredients`);
      if (source.pin) {
        log.item('    pin', source.pin);
      }
    }
  }

  // ── Workspace ──────────────────────────────────────────────────────────────
  log.info('');
  log.header('Workspace\n');
  log.item('  cwd', workspaceRoot);

  const stack = await detectStack(workspaceRoot);
  const techList = [...stack.technologies].sort().join(', ');
  log.item('  stack', techList || '(none detected)');

  if (config.sources.length > 0) {
    const allIngredients: IngredientFile[] = [];
    const allMappings: ExternalMapping[] = [];

    for (const source of config.sources) {
      const { ingredients, mappings } = await collectIngredients(source);
      allIngredients.push(...ingredients);
      allMappings.push(...mappings);
    }

    const projectId = getProjectId(workspaceRoot);
    const privacyConfig = await loadPrivacyConfig(projectId);

    const allMatches = matchIngredients(allIngredients, stack, allMappings);
    const excludedSet = new Set(privacyConfig.excludedIngredients);
    const matches = allMatches.filter(
      (m) => !excludedSet.has(`${m.ingredient.sourceName}/${m.ingredient.relativePath}`),
    );
    const excludedCount = allMatches.length - matches.length;

    const { publicMatches, privateMatches } = splitByPrivacy(matches, privacyConfig);

    const publicLabel = publicMatches.length > 0 ? `${publicMatches.length} public` : null;
    const privateLabel = privateMatches.length > 0 ? `${privateMatches.length} private` : null;
    const matchSummaryParts = [publicLabel, privateLabel].filter(Boolean);
    const matchSummary =
      matchSummaryParts.length > 0
        ? matchSummaryParts.join(', ')
        : '0 matched';

    log.item('  matches', matchSummary);
    if (excludedCount > 0) {
      log.item('  excluded', `${excludedCount}`);
    }
  }

  // ── Targets ────────────────────────────────────────────────────────────────
  log.info('');
  log.header('Targets\n');

  if (config.customTargets && config.customTargets.length > 0) {
    registerCustomTargets(config.customTargets);
  }

  const registry = getTargetRegistry();
  const activeTargetIds = config.settings.targets;

  for (const targetId of activeTargetIds) {
    const target = registry.get(targetId);
    if (!target) continue;

    const outputPath = join(workspaceRoot, target.outputPath);
    const exists = await fileExists(outputPath);

    if (!exists) {
      log.info(`  ${targetId}`);
      log.item('    file', target.outputPath);
      log.hint(`    status: not generated`);
      continue;
    }

    const content = await readText(outputPath);
    const hasOldSentinel = content.trimStart().startsWith('# Generated by ingred');
    const hasSentinel =
      content.trimStart().startsWith(INGRED_SENTINEL) || hasOldSentinel;

    log.info(`  ${targetId}`);
    log.item('    file', target.outputPath);
    if (hasSentinel) {
      log.item('    status', 'managed by ingred');
    } else {
      log.item('    status', 'manual file (not managed by ingred)');
    }
  }
}
