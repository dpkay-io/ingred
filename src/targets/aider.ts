import type { Target, CompiledOutput, DetectedStack } from '../types.js';

const AIDER_SENTINEL = '# Generated by ingred. Do not edit manually. Run `ingred mix` to regenerate.';

export const aider: Target = {
  id: 'aider',
  outputPath: '.aider.conf.yml',
  format(compiled: CompiledOutput, _stack: DetectedStack): string {
    const hasPersona = !!compiled.personaSection;
    const hasEngineering = !!compiled.engineeringSection;

    if (!hasPersona && !hasEngineering) {
      return AIDER_SENTINEL + '\n';
    }

    const contentLines: string[] = [];

    if (hasPersona) {
      contentLines.push('# Style');
      for (const line of compiled.personaSection.split('\n')) {
        contentLines.push('  ' + line);
      }
    }

    if (hasEngineering) {
      if (contentLines.length > 0) {
        contentLines.push('');
      }
      contentLines.push('# Rules');
      for (const line of compiled.engineeringSection.split('\n')) {
        contentLines.push('  ' + line);
      }
    }

    const parts: string[] = [
      AIDER_SENTINEL,
      'conventions: |',
      ...contentLines,
    ];

    return parts.join('\n') + '\n';
  },
  privateReference(compiledDir: string): string {
    return `# Read and follow: ${compiledDir}/private-aider.md`;
  },
};
