import { join, basename } from 'node:path';
import { writeFile, unlink } from 'node:fs/promises';
import { fileExists, readText, ensureDir as ensureDirExists } from '../utils/fs.js';
import type {
  CompileResult,
  CompiledOutput,
  CustomTargetConfig,
  DetectedStack,
  EmitResult,
  Target,
  TargetId,
} from '../types.js';
import { resolveTemplateVars, type TemplateVars } from './template.js';
import { INGRED_SENTINEL } from '../types.js';
import { claude } from '../targets/claude.js';
import { cursor } from '../targets/cursor.js';
import { copilot } from '../targets/copilot.js';
import { agents } from '../targets/agents.js';
import { gemini } from '../targets/gemini.js';
import { windsurf } from '../targets/windsurf.js';
import { cline } from '../targets/cline.js';
import { aider } from '../targets/aider.js';

export interface PrivateEmitOptions {
  privateCompiled: CompileResult | null;
  compiledDir: string;
  tildeCompiledDir: string;
}

const TARGET_REGISTRY: Map<TargetId | string, Target> = new Map([
  ['claude', claude],
  ['cursor', cursor],
  ['copilot', copilot],
  ['agents', agents],
  ['gemini', gemini],
  ['windsurf', windsurf],
  ['cline', cline],
  ['aider', aider],
]);

function hasContent(compiled: CompiledOutput): boolean {
  return compiled.personaSection.length > 0 || compiled.engineeringSection.length > 0;
}

function resolveCompiledOutput(output: CompiledOutput, vars: TemplateVars): CompiledOutput {
  return {
    personaSection: resolveTemplateVars(output.personaSection, vars),
    engineeringSection: resolveTemplateVars(output.engineeringSection, vars),
  };
}

function mergeOutputs(a: CompiledOutput, b: CompiledOutput): CompiledOutput {
  return {
    personaSection: [a.personaSection, b.personaSection].filter(Boolean).join('\n\n'),
    engineeringSection: [a.engineeringSection, b.engineeringSection].filter(Boolean).join('\n\n'),
  };
}

async function writeTarget(
  target: Target,
  compiled: CompiledOutput,
  stack: DetectedStack,
  outputPath: string,
  force: boolean,
  location: 'project' | 'global',
  privateRef?: string,
): Promise<EmitResult> {
  if (target.ensureDir && location === 'project') {
    await ensureDirExists(join(stack.workspaceRoot, target.ensureDir));
  }
  if (target.globalEnsureDir && location === 'global') {
    await ensureDirExists(target.globalEnsureDir);
  }

  if (await fileExists(outputPath)) {
    const existing = await readText(outputPath);
    const startsWithSentinel =
      existing.trimStart().startsWith(INGRED_SENTINEL) ||
      existing.trimStart().startsWith('# Generated by ingred');
    if (!startsWithSentinel) {
      if (!force) {
        return {
          target: target.id,
          location,
          status: 'skipped',
          path: outputPath,
          reason: 'existing manual file detected',
        };
      }
    }
  }

  let formatted = target.format(compiled, stack);
  if (privateRef) {
    formatted = formatted.trimEnd() + '\n\n' + privateRef + '\n';
  }
  await writeFile(outputPath, formatted, 'utf-8');
  return { target: target.id, location, status: 'written', path: outputPath };
}

async function writePrivateTarget(
  target: Target,
  compiled: CompiledOutput,
  stack: DetectedStack,
  compiledDir: string,
): Promise<void> {
  await ensureDirExists(compiledDir);
  const formatted = target.format(compiled, stack);
  // Strip the sentinel comment from private files (they aren't user-facing)
  const stripped = formatted
    .replace(INGRED_SENTINEL + '\n', '')
    .replace(INGRED_SENTINEL, '')
    .replace('# Generated by ingred. Do not edit manually. Run `ingred mix` to regenerate.\n', '')
    .replace('# Generated by ingred. Do not edit manually. Run `ingred mix` to regenerate.', '');
  await writeFile(join(compiledDir, `private-${target.id}.md`), stripped, 'utf-8');
}

async function cleanupStalePrivateFile(
  targetId: TargetId | string,
  compiledDir: string,
): Promise<void> {
  const filePath = join(compiledDir, `private-${targetId}.md`);
  if (await fileExists(filePath)) {
    await unlink(filePath);
  }
}

const BUILTIN_TARGET_IDS = new Set<string>([
  'claude', 'cursor', 'copilot', 'agents', 'gemini', 'windsurf', 'cline', 'aider',
]);

type CommentSyntax = 'html' | 'js' | 'hash' | 'none';

function makeSentinel(commentSyntax: CommentSyntax): string {
  const msg = 'Generated by ingred. Do not edit manually. Run `ingred mix` to regenerate.';
  switch (commentSyntax) {
    case 'html': return `<!-- ${msg} -->`;
    case 'js':   return `/* ${msg} */`;
    case 'hash': return `# ${msg}`;
    case 'none': return '';
  }
}

function makeComment(text: string, commentSyntax: CommentSyntax): string {
  switch (commentSyntax) {
    case 'html': return `<!-- ${text} -->`;
    case 'js':   return `/* ${text} */`;
    case 'hash': return `# ${text}`;
    case 'none': return text;
  }
}

export function buildCustomTarget(config: CustomTargetConfig): Target {
  if (BUILTIN_TARGET_IDS.has(config.id)) {
    throw new Error(`Custom target ID "${config.id}" collides with built-in target.`);
  }

  const { commentSyntax } = config.format;

  return {
    id: config.id,
    outputPath: config.outputPath,
    format(compiled: CompiledOutput, _stack: DetectedStack): string {
      const parts: string[] = [];

      const sentinel = makeSentinel(commentSyntax);
      if (sentinel) parts.push(sentinel);

      if (config.format.header) {
        parts.push('', config.format.header);
      }

      if (compiled.personaSection) {
        if (config.format.personaHeader) {
          parts.push('', config.format.personaHeader);
        }
        parts.push('', compiled.personaSection);
      }

      if (compiled.engineeringSection) {
        if (config.format.engineeringHeader) {
          parts.push('', config.format.engineeringHeader);
        }
        parts.push('', compiled.engineeringSection);
      }

      return parts.join('\n') + '\n';
    },
    privateReference(compiledDir: string): string {
      return makeComment(
        `Read and follow: ${compiledDir}/private-${config.id}.md`,
        commentSyntax,
      );
    },
  };
}

export function registerCustomTargets(customConfigs: CustomTargetConfig[]): void {
  for (const config of customConfigs) {
    const target = buildCustomTarget(config);
    TARGET_REGISTRY.set(target.id as TargetId, target);
  }
}

export function getTargetRegistry(): ReadonlyMap<TargetId | string, Target> {
  return TARGET_REGISTRY;
}

export async function emit(
  result: CompileResult,
  stack: DetectedStack,
  targets: TargetId[],
  force: boolean,
  privateOpts?: PrivateEmitOptions,
): Promise<EmitResult[]> {
  const results: EmitResult[] = [];

  const baseTemplateVars = {
    stack: [...stack.technologies].sort().join(', '),
    workspace: basename(stack.workspaceRoot),
    date: new Date().toISOString().slice(0, 10),
  };

  for (const targetId of targets) {
    const target = TARGET_REGISTRY.get(targetId);
    if (!target) continue;

    const templateVars: TemplateVars = { ...baseTemplateVars, target: targetId };

    const resolvedGlobal = resolveCompiledOutput(result.global, templateVars);
    const resolvedProject = resolveCompiledOutput(result.project, templateVars);

    if (target.globalOutputPath && hasContent(resolvedGlobal)) {
      const globalResult = await writeTarget(
        target,
        resolvedGlobal,
        stack,
        target.globalOutputPath,
        force,
        'global',
      );
      results.push(globalResult);
    }

    const projectCompiled = target.globalOutputPath
      ? resolvedProject
      : mergeOutputs(resolvedGlobal, resolvedProject);

    // Determine private reference for this target
    let privateRef: string | undefined;
    if (privateOpts) {
      const privateProjectCompiled = privateOpts.privateCompiled
        ? resolveCompiledOutput(
            mergeOutputs(privateOpts.privateCompiled.global, privateOpts.privateCompiled.project),
            templateVars,
          )
        : null;

      if (privateProjectCompiled && hasContent(privateProjectCompiled)) {
        await writePrivateTarget(target, privateProjectCompiled, stack, privateOpts.compiledDir);
        privateRef = target.privateReference(privateOpts.tildeCompiledDir);
      } else {
        // No private content — clean up stale file if privateOpts was provided
        await cleanupStalePrivateFile(targetId, privateOpts.compiledDir);
      }
    }

    if (hasContent(projectCompiled) || privateRef) {
      const projectPath = join(stack.workspaceRoot, target.outputPath);
      const projectResult = await writeTarget(
        target,
        projectCompiled,
        stack,
        projectPath,
        force,
        'project',
        privateRef,
      );
      results.push(projectResult);
    }
  }

  return results;
}
