import { describe, it } from 'node:test';
import assert from 'node:assert/strict';
import { windsurf } from '../../src/targets/windsurf.js';
import { cline } from '../../src/targets/cline.js';
import { aider } from '../../src/targets/aider.js';
import { INGRED_SENTINEL } from '../../src/types.js';
import type { CompiledOutput, DetectedStack } from '../../src/types.js';

function makeStack(): DetectedStack {
  return {
    technologies: new Set<string>(),
    detectedFiles: new Map(),
    workspaceRoot: '/tmp/test',
  };
}

function makeCompiled(persona = '', engineering = ''): CompiledOutput {
  return { personaSection: persona, engineeringSection: engineering };
}

// ── windsurf ───────────────────────────────────────────────────────────────

describe('windsurf target', () => {
  it('has correct id and outputPath', () => {
    assert.equal(windsurf.id, 'windsurf');
    assert.equal(windsurf.outputPath, '.windsurfrules');
  });

  it('format includes sentinel', () => {
    const out = windsurf.format(makeCompiled('', 'Be strict'), makeStack());
    assert.ok(out.startsWith(INGRED_SENTINEL));
  });

  it('format with both sections uses section headers', () => {
    const out = windsurf.format(makeCompiled('Be friendly', 'Be strict'), makeStack());
    assert.ok(out.includes('## Interaction Style'));
    assert.ok(out.includes('Be friendly'));
    assert.ok(out.includes('## Coding Standards'));
    assert.ok(out.includes('Be strict'));
  });

  it('format with persona only omits section headers', () => {
    const out = windsurf.format(makeCompiled('Be friendly', ''), makeStack());
    assert.ok(out.includes('Be friendly'));
    assert.ok(!out.includes('## Interaction Style'));
    assert.ok(!out.includes('## Coding Standards'));
  });

  it('format with engineering only omits section headers', () => {
    const out = windsurf.format(makeCompiled('', 'Be strict'), makeStack());
    assert.ok(out.includes('Be strict'));
    assert.ok(!out.includes('## Interaction Style'));
    assert.ok(!out.includes('## Coding Standards'));
  });

  it('format ends with newline', () => {
    const out = windsurf.format(makeCompiled('', 'rules'), makeStack());
    assert.ok(out.endsWith('\n'));
  });

  it('privateReference uses HTML comment style with correct filename', () => {
    const ref = windsurf.privateReference('/home/user/.ingred/compiled/abc');
    assert.ok(ref.startsWith('<!--'));
    assert.ok(ref.includes('/home/user/.ingred/compiled/abc/private-windsurf.md'));
  });
});

