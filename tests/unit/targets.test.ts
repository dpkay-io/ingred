// ── aider ──────────────────────────────────────────────────────────────────

const AIDER_SENTINEL = '# Generated by ingred. Do not edit manually. Run `ingred mix` to regenerate.';

describe('aider target', () => {
  it('has correct id and outputPath', () => {
    assert.equal(aider.id, 'aider');
    assert.equal(aider.outputPath, '.aider.conf.yml');
  });

  it('format starts with hash-comment sentinel (not HTML sentinel)', () => {
    const out = aider.format(makeCompiled('', 'use types'), makeStack());
    assert.ok(out.startsWith(AIDER_SENTINEL));
    assert.ok(!out.startsWith('<!--'));
  });

  it('format with both sections produces valid YAML with conventions key', () => {
    const out = aider.format(makeCompiled('Be terse', 'Use types'), makeStack());
    assert.ok(out.includes('conventions: |'));
    assert.ok(out.includes('# Style'));
    assert.ok(out.includes('  Be terse'));
    assert.ok(out.includes('# Rules'));
    assert.ok(out.includes('  Use types'));
  });

  it('format with persona only includes Style comment and indented content', () => {
    const out = aider.format(makeCompiled('Be terse', ''), makeStack());
    assert.ok(out.includes('conventions: |'));
    assert.ok(out.includes('# Style'));
    assert.ok(out.includes('  Be terse'));
    assert.ok(!out.includes('# Rules'));
  });

  it('format with engineering only includes Rules comment and indented content', () => {
    const out = aider.format(makeCompiled('', 'Use types'), makeStack());
    assert.ok(out.includes('conventions: |'));
    assert.ok(!out.includes('# Style'));
    assert.ok(out.includes('# Rules'));
    assert.ok(out.includes('  Use types'));
  });

  it('format with no content still starts with sentinel', () => {
    const out = aider.format(makeCompiled('', ''), makeStack());
    assert.ok(out.startsWith(AIDER_SENTINEL));
    assert.ok(!out.includes('conventions: |'));
  });

  it('format ends with newline', () => {
    const out = aider.format(makeCompiled('', 'rules'), makeStack());
    assert.ok(out.endsWith('\n'));
  });

  it('engineering content lines are indented by two spaces', () => {
    const out = aider.format(makeCompiled('', 'first line\nsecond line'), makeStack());
    assert.ok(out.includes('  first line'));
    assert.ok(out.includes('  second line'));
  });

  it('privateReference uses hash comment style with correct filename', () => {
    const ref = aider.privateReference('/home/user/.ingred/compiled/abc');
    assert.ok(ref.startsWith('#'));
    assert.ok(ref.includes('/home/user/.ingred/compiled/abc/private-aider.md'));
  });
});
