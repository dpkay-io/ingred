// ── none comment syntax ────────────────────────────────────────────────────

describe('buildCustomTarget - none comment syntax', () => {
  const target = buildCustomTarget(makeConfig({ format: { commentSyntax: 'none' } }));

  it('format does not start with a comment', () => {
    const out = target.format(makeCompiled('', 'rule'), makeStack());
    assert.ok(!out.startsWith('<!--'));
    assert.ok(!out.startsWith('#'));
    assert.ok(!out.startsWith('/*'));
  });

  it('privateReference returns plain text (no comment markers)', () => {
    const ref = target.privateReference('/home/user/.ingred/compiled/abc');
    assert.ok(!ref.startsWith('<!--'));
    assert.ok(!ref.startsWith('#'));
    assert.ok(!ref.startsWith('/*'));
    assert.ok(ref.includes('/home/user/.ingred/compiled/abc/private-myeditor.md'));
  });
});

// ── format output ──────────────────────────────────────────────────────────

describe('buildCustomTarget - format output', () => {
  it('includes global header when defined', () => {
    const target = buildCustomTarget(makeConfig({
      format: { commentSyntax: 'html', header: '## My Custom Rules' },
    }));
    const out = target.format(makeCompiled('', 'rule'), makeStack());
    assert.ok(out.includes('## My Custom Rules'));
  });

  it('includes personaHeader before persona section', () => {
    const target = buildCustomTarget(makeConfig({
      format: { commentSyntax: 'html', personaHeader: '## Style' },
    }));
    const out = target.format(makeCompiled('Be concise', ''), makeStack());
    assert.ok(out.includes('## Style'));
    assert.ok(out.includes('Be concise'));
    const styleIdx = out.indexOf('## Style');
    const contentIdx = out.indexOf('Be concise');
    assert.ok(styleIdx < contentIdx, 'personaHeader should appear before persona content');
  });

  it('includes engineeringHeader before engineering section', () => {
    const target = buildCustomTarget(makeConfig({
      format: { commentSyntax: 'html', engineeringHeader: '## Engineering' },
    }));
    const out = target.format(makeCompiled('', 'No magic numbers'), makeStack());
    assert.ok(out.includes('## Engineering'));
    assert.ok(out.includes('No magic numbers'));
    const headerIdx = out.indexOf('## Engineering');
    const contentIdx = out.indexOf('No magic numbers');
    assert.ok(headerIdx < contentIdx, 'engineeringHeader should appear before engineering content');
  });

  it('omits personaHeader when persona section is empty', () => {
    const target = buildCustomTarget(makeConfig({
      format: { commentSyntax: 'html', personaHeader: '## Style' },
    }));
    const out = target.format(makeCompiled('', 'some rule'), makeStack());
    assert.ok(!out.includes('## Style'));
  });

  it('omits engineeringHeader when engineering section is empty', () => {
    const target = buildCustomTarget(makeConfig({
      format: { commentSyntax: 'html', engineeringHeader: '## Engineering' },
    }));
    const out = target.format(makeCompiled('some persona', ''), makeStack());
    assert.ok(!out.includes('## Engineering'));
  });

  it('format ends with newline', () => {
    const target = buildCustomTarget(makeConfig());
    const out = target.format(makeCompiled('', 'rule'), makeStack());
    assert.ok(out.endsWith('\n'));
  });

  it('id and outputPath are preserved from config', () => {
    const target = buildCustomTarget(makeConfig({ id: 'zed-rules', outputPath: '.zed/rules.md' }));
    assert.equal(target.id, 'zed-rules');
    assert.equal(target.outputPath, '.zed/rules.md');
  });
});

// ── registerCustomTargets / getTargetRegistry ──────────────────────────────

describe('registerCustomTargets and getTargetRegistry', () => {
  it('registers custom targets into the registry', () => {
    const configs: CustomTargetConfig[] = [
      { id: 'test-target-a', outputPath: '.test-a', format: { commentSyntax: 'hash' } },
      { id: 'test-target-b', outputPath: '.test-b', format: { commentSyntax: 'js' } },
    ];
    registerCustomTargets(configs);

    const registry = getTargetRegistry();
    assert.ok(registry.has('test-target-a' as never));
    assert.ok(registry.has('test-target-b' as never));
  });

  it('registered target produces correct output', () => {
    const configs: CustomTargetConfig[] = [
      {
        id: 'test-target-c',
        outputPath: '.test-c',
        format: { commentSyntax: 'hash', engineeringHeader: '## Rules' },
      },
    ];
    registerCustomTargets(configs);

    const registry = getTargetRegistry();
    const target = registry.get('test-target-c' as never);
    assert.ok(target, 'target should be in registry');

    const out = target!.format(makeCompiled('', 'keep it simple'), makeStack());
    assert.ok(out.startsWith('# Generated by ingred.'));
    assert.ok(out.includes('## Rules'));
    assert.ok(out.includes('keep it simple'));
  });

  it('getTargetRegistry includes all built-in targets', () => {
    const registry = getTargetRegistry();
    const builtins = ['claude', 'cursor', 'copilot', 'agents', 'gemini', 'windsurf', 'cline', 'aider'];
    for (const id of builtins) {
      assert.ok(registry.has(id as never), `registry should contain built-in target: ${id}`);
    }
  });
});
