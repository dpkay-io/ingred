import { describe, it } from 'node:test';
import assert from 'node:assert/strict';
import { buildCustomTarget, registerCustomTargets, getTargetRegistry } from '../../src/core/emitter.js';
import type { CustomTargetConfig, CompiledOutput, DetectedStack } from '../../src/types.js';

function makeStack(): DetectedStack {
  return {
    technologies: new Set<string>(),
    detectedFiles: new Map(),
    workspaceRoot: '/tmp/test',
  };
}

function makeCompiled(persona = '', engineering = ''): CompiledOutput {
  return { personaSection: persona, engineeringSection: engineering };
}

function makeConfig(overrides: Partial<CustomTargetConfig> = {}): CustomTargetConfig {
  return {
    id: 'myeditor',
    outputPath: '.myeditor-rules',
    format: {
      commentSyntax: 'html',
    },
    ...overrides,
  };
}

// ── collision detection ────────────────────────────────────────────────────

describe('buildCustomTarget - collision detection', () => {
  const builtinIds = ['claude', 'cursor', 'copilot', 'agents', 'gemini', 'windsurf', 'cline', 'aider'];

  for (const id of builtinIds) {
    it(`throws when id collides with built-in target: ${id}`, () => {
      assert.throws(
        () => buildCustomTarget(makeConfig({ id })),
        (err: unknown) => {
          assert.ok(err instanceof Error);
          assert.ok(err.message.includes(id));
          assert.ok(err.message.includes('collides with built-in target'));
          return true;
        },
      );
    });
  }

  it('does not throw for a non-colliding id', () => {
    assert.doesNotThrow(() => buildCustomTarget(makeConfig({ id: 'custom-one' })));
  });
});

// ── html comment syntax ────────────────────────────────────────────────────

describe('buildCustomTarget - html comment syntax', () => {
  const target = buildCustomTarget(makeConfig({ format: { commentSyntax: 'html' } }));

  it('format starts with HTML sentinel', () => {
    const out = target.format(makeCompiled('', 'rule'), makeStack());
    assert.ok(out.startsWith('<!-- Generated by ingred.'));
  });

  it('privateReference uses HTML comment', () => {
    const ref = target.privateReference('/home/user/.ingred/compiled/abc');
    assert.ok(ref.startsWith('<!--'));
    assert.ok(ref.includes('/home/user/.ingred/compiled/abc/private-myeditor.md'));
    assert.ok(ref.endsWith('-->'));
  });
});

